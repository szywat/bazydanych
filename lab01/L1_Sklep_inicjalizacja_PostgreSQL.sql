-- Laboratorium 1: powtórzenie SQL i relacyjnych baz danych
-- PostgreSQL. Kodowanie UTF-8. Dane fikcyjne.
-- Uruchom cały skrypt w pgAdmin (Query Tool) w istniejącej bazie ćwiczeniowej.
-- Skrypt tworzy osobny schemat l1_sklep i nie usuwa istniejących danych.
-- Jeśli schemat już istnieje, CREATE SCHEMA zgłosi błąd i transakcja
-- nie zostanie zatwierdzona. Wykonaj ROLLBACK przed kolejną próbą.
-- Aby ZRESETOWAĆ wyłącznie dane tego ćwiczenia, świadomie uruchom osobno:
-- DROP SCHEMA l1_sklep CASCADE;
-- Następnie ponownie uruchom cały ten skrypt.
-- W nowym oknie lub po ponownym połączeniu ustaw:
-- SET search_path TO l1_sklep, public;
-- Skrypt zawiera dane startowe, bez rozwiązań zadań.
-- Stany magazynowe oznaczają aktualne dostępne ilości po wcześniejszych operacjach.
-- Brak automatycznych triggerów zmiany stanu: aktualizację wykonuje student.

BEGIN;
CREATE SCHEMA l1_sklep;
SET search_path TO l1_sklep, public;

CREATE TABLE klienci (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imie VARCHAR(60) NOT NULL,
    nazwisko VARCHAR(80) NOT NULL,
    email VARCHAR(160) NOT NULL,
    miasto VARCHAR(80) NOT NULL,
    CONSTRAINT uq_klienci_email UNIQUE (email)
);

CREATE TABLE produkty (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nazwa VARCHAR(160) NOT NULL,
    kategoria VARCHAR(60) NOT NULL,
    cena NUMERIC(10,2) NOT NULL,
    stan_magazynowy INTEGER NOT NULL,
    CONSTRAINT ck_produkty_cena CHECK (cena >= 0),
    CONSTRAINT ck_produkty_stan CHECK (stan_magazynowy >= 0)
);

CREATE TABLE zamowienia (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    klienci_id INTEGER NOT NULL,
    data_zamowienia DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT fk_zamowienia_klient FOREIGN KEY (klienci_id)
        REFERENCES klienci(id),
    CONSTRAINT ck_zamowienia_status CHECK
        (status IN ('nowe', 'oplacone', 'wyslane', 'anulowane'))
);

CREATE TABLE pozycje_zamowien (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zamowienia_id INTEGER NOT NULL,
    produkty_id INTEGER NOT NULL,
    ilosc INTEGER NOT NULL,
    cena_jednostkowa NUMERIC(10,2) NOT NULL,
    CONSTRAINT uq_pozycje_zamowienie_produkt UNIQUE (zamowienia_id, produkty_id),
    CONSTRAINT fk_pozycje_zamowienie FOREIGN KEY (zamowienia_id)
        REFERENCES zamowienia(id),
    CONSTRAINT fk_pozycje_produkt FOREIGN KEY (produkty_id)
        REFERENCES produkty(id),
    CONSTRAINT ck_pozycje_ilosc CHECK (ilosc > 0),
    CONSTRAINT ck_pozycje_cena CHECK (cena_jednostkowa >= 0)
);

